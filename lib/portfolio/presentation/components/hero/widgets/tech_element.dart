class TechElement {
  final double startX;
  final double startY;
  final double speedY;
  final double size;
  final double opacity;
  final bool isOutline;

  TechElement({
    required this.startX,
    required this.startY,
    required this.speedY,
    required this.size,
    required this.opacity,
    required this.isOutline,
  });
}
